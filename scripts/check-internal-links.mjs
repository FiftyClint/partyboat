#!/usr/bin/env node
import { readFileSync, readdirSync } from 'node:fs';
import { builtPages } from './lib/html-text.mjs';
import { parse } from 'node-html-parser';

/**
 * Every URL we publish for ourselves has to be the URL the page is served at.
 *
 * build.format is 'directory', so a route at /about is written to
 * about/index.html and served at /about/. The canonical tag says /about/ and
 * the sitemap lists /about/. Anything of ours that links to /about instead is
 * publishing an address that disagrees with the page it points at, and we then
 * rely on the host to paper over it.
 *
 * This has now been got wrong three times in the same codebase, each time in a
 * different emitter, each time found by something outside the build:
 *
 *   August. The canonical tag itself. Two weeks after launch every one of the
 *   nineteen domains had exactly one page indexed and it was the homepage,
 *   which was the only page whose path already ended in a slash.
 *
 *   8 September. JSON-LD. All 243 pages declared one URL in the head tag and a
 *   different one in their structured data. Eleven days green, because
 *   check-canonicals only read the head tag.
 *
 *   24 September. Internal links and llms.txt. Every navigation and footer
 *   link on all 275 pages, and 161 of the 198 links in llms.txt, still used
 *   the slashless form. llms.txt is the file written specifically for crawlers
 *   that do not read canonical tags, so it was the worst place for it.
 *
 * The fix each time was local. This check is the general one: it takes every
 * self-referential URL in the built output, from anchors, from
 * sitemaps, and requires each to be a canonical some page in that build
 * declares. A fourth emitter getting this wrong fails here instead.
 */

const ROOT = new URL('..', import.meta.url).pathname;
const DIST = `${ROOT}dist`;

const pages = builtPages(DIST);
if (pages.length === 0) {
  console.error('No built pages found. Run npm run build:all first.');
  process.exit(1);
}

/* Canonical each page declares for itself, grouped by site. */
const canonicalsBySite = new Map();
const originBySite = new Map();
for (const page of pages) {
  const m = page.html.match(/<link rel="canonical" href="([^"]+)"/i);
  if (!m) continue;
  if (!canonicalsBySite.has(page.site)) canonicalsBySite.set(page.site, new Set());
  canonicalsBySite.get(page.site).add(m[1]);
  originBySite.set(page.site, new URL(m[1]).origin);
}

const problems = [];

/*
 * Anchors. Only our own paths are checked. An external link is somebody
 * else's business, a mailto or an anchor-only href has no page behind it, and
 * a fragment is stripped before comparing because /ohio/#faq-heading is the
 * same document as /ohio/.
 */
for (const page of pages) {
  const origin = originBySite.get(page.site);
  if (!origin) continue;
  const seen = new Set();
  for (const a of parse(page.html).querySelectorAll('a[href]')) {
    const href = a.getAttribute('href') || '';
    if (!href.startsWith('/') || href.startsWith('//')) continue;
    const url = new URL(href, origin);
    const target = `${url.origin}${url.pathname}`;
    if (seen.has(target)) continue;
    seen.add(target);
    if (!canonicalsBySite.get(page.site).has(target)) {
      problems.push({
        where: `${page.site}${page.path}`,
        kind: 'anchor',
        link: href,
        target,
      });
    }
  }
}

/* Sitemaps. Generated by the integration, so this is a guard rather than a fear. */
for (const site of readdirSync(DIST)) {
  let xml;
  try {
    xml = readFileSync(`${DIST}/${site}/sitemap-0.xml`, 'utf8');
  } catch {
    continue;
  }
  const canon = canonicalsBySite.get(site);
  if (!canon) continue;
  for (const match of xml.matchAll(/<loc>([^<]+)<\/loc>/g)) {
    if (!canon.has(match[1])) {
      problems.push({ where: `${site}/sitemap-0.xml`, kind: 'sitemap', link: match[1], target: match[1] });
    }
  }
}

if (problems.length > 0) {
  const byKind = {};
  for (const p of problems) byKind[p.kind] = (byKind[p.kind] ?? 0) + 1;
  console.error(
    `Internal link check FAILED. ${problems.length} link(s) point at a URL that no\n` +
      'page in the build declares as its canonical.\n',
  );
  console.error(`  by kind: ${JSON.stringify(byKind)}\n`);
  for (const p of problems.slice(0, 25)) {
    console.error(`  ${p.where}`);
    console.error(`    links to ${p.link || '(nothing)'}`);
    if (p.target) console.error(`    resolved  ${p.target}`);
  }
  if (problems.length > 25) console.error(`\n  ...and ${problems.length - 25} more.`);
  console.error(
    '\nFix by building the path with internalPath() from src/lib/nav.mjs, which\n' +
      'guarantees the trailing slash the directory build actually serves. Do not\n' +
      'add the slash by hand at the call site: that is how the last three of\n' +
      'these happened.',
  );
  process.exit(1);
}

const anchorCount = pages.length;
console.log(
  `Internal link check passed. Every self-referential link across ${anchorCount} ` +
    `page(s) and their sitemaps resolves to a ` +
    'canonical the build declares.',
);
